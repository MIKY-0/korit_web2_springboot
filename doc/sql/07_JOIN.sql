/*
JOIN : 여러 테이블을 좌우로 연결해서 하나의 결과를 만드는 방법. 연결하는 역할 해주는게 FK.
#주문 + 고객 조회.
INNER JOIN : 두 테이블 모두에서 매칭되는 값이 있는 ROW만 가져옴.
ON : JOIN시킬 조건. O.CUSTOMER_ID = C.CUSTOMER_ID인것을 가져와라.
매칭 안될 경우 해당 ROW 가져오지 않음.
---ON과 WHERE차이
ON : 조인조건으로 두 테이블을 합쳐서 새로운 가상테이블을 만드는것.
WHERE : 테이블에 조건을 걸어 필터링.
*/
SELECT O.ORDER_ID , O.ORDER_DATE , O.CUSTOMER_ID , C.CUSTOMER_NAME 
FROM ORDERS O INNER JOIN CUSTOMERS C ON O.CUSTOMER_ID = C.CUSTOMER_ID;

# 주문(ORDERS) + 주문상세(ORDER_DETAILS) + 상품이름(PRODUCT)
 SELECT O.ORDER_ID , O.ORDER_DATE , O.CUSTOMER_ID , C.CUSTOMER_NAME , P.PRODUCT_NAME
 FROM ORDERS O INNER JOIN CUSTOMER C ON O.CUSTOMER_ID = C.CUSTOMER_ID
			   INNER JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
			   INNER JOIN PRODUCT P ON OD.PRODUCT_ID = P.PRODUCT_ID;
			            
#LEFT JOIN : 왼쪽 테이블은 모두 가져오고 오른쪽 테이블은 매칭되는 것만.(우측에 NULL 표시)
#고객이 주문했는지 여부 : CUSTOMERS LEFT JOIN ORDERS
SELECT C.CUSTOMER_NAME , O.ORDER_ID , O.ORDER_DATE # CUSTOMER LEFT JOIN ORDERS -> 전체 고객기준으로 ORDERS 데이터를 붙히겠다. 
FROM CUSTOMERS C LEFT JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID;

